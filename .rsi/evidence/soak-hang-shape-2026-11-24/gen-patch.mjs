// Renders the one overlay this round runs.
//
//   node gen-patch.mjs
//
// Writes scenario-hang.yml next to this file. The only thing that distinguishes
// this scenario from the 0.13.29 rig is the worker chain: the route under test
// hangs forever on every request, so the run has to pay it and then stop
// preferring it.
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
// The shipped build is the primary evidence. A copy under .tmp/ with exactly one
// line flipped (renderReport(value) -> renderReport(value, { showDiagnostics: true }))
// renders the ledger the shipped build keeps hardcoded off; routing, retry, budget
// and reporting decisions are byte-identical (see README "Honest gaps").
const PLUGIN_ENTRY = process.env.SOAK_PLUGIN_ENTRY
  ?? '/home/fish/projects_mine/dsh-grok-workflow/lib/index.js'
const SUFFIX = process.env.SOAK_SUFFIX ?? ''

// 45 s: the slowest live child call measured on this machine is ~10.4 s
// (synthesizer; worker ~6.2 s — see .rsi/evidence/soak-release-01329/README.md
// §Budget), so this is a >=4x margin. A live call always finishes; a hung one
// always dies. Two hang settlements cost 2 x 45 s of wall clock.
const CHILD_TIMEOUT_MS = Number(process.env.CHILD_TIMEOUT_MS ?? 45000)
// The outer agent talks to the machine's gateway directly, so its model id has
// to be one that gateway really serves right now. wb/cn is 503
// no_healthy_account on this machine; wb/global is 200 healthy, same gateway,
// same key, one routing group over (README "Honest gaps").
const LIVE_MODEL = process.env.SOAK_LIVE_MODEL ?? 'wb/global:deepseek-v4.1-flash'

function providerBlock(id, display, port, models) {
  const entries = models
    .map(model => `          - id: ${model}\n            name: ${model}\n            contextWindow: 500000\n            maxTokens: 65536`)
    .join('\n')
  return `      ${id}:
        displayName: ${JSON.stringify(display)}
        api: openai-completions
        baseURL: http://127.0.0.1:${port}/openai/v1
        apiKeyEnv: BIFROST_VIRTUAL_KEY
        compat:
          supportsDeveloperRole: false
          supportsStore: false
        models:
${entries}`
}

const live = `      soak-live:
        displayName: Soak live (the machine's own gateway, direct — the outer agent and planning legs use this)
        api: openai-completions
        baseURL: http://127.0.0.1:18088/openai/v1
        apiKeyEnv: BIFROST_VIRTUAL_KEY
        compat:
          supportsDeveloperRole: false
          supportsStore: false
        models:
          - id: ${LIVE_MODEL}
            name: soak live flash
            contextWindow: 500000
            maxTokens: 65536`

const pool = providerBlock('soak-pool', 'Soak pool (18593, proxies to the live gateway)', 18593, [
  'soak/plan-live',
  'soak/work-live',
  'soak/judge-live',
  'soak/sup-live',
  'soak/synth-live',
])
const hang = providerBlock('soak-hang', 'Soak hang 18591 — the route under test: never answers', 18591, [
  'soak/hang-always',
])
const auth = providerBlock('soak-auth', 'Soak auth (18592, every completion 401 — unused this round)', 18592, [
  'soak/auth-bad',
])

const roles = [
  ['planner', [{ provider: 'soak-live', model: LIVE_MODEL }]],
  [
    'worker',
    [
      { provider: 'soak-hang', model: 'soak/hang-always' },
      { provider: 'soak-pool', model: 'soak/work-live' },
    ],
  ],
  ['verifier', [{ provider: 'soak-pool', model: 'soak/judge-live' }]],
  ['supervisor', [{ provider: 'soak-pool', model: 'soak/sup-live' }]],
  ['synthesizer', [{ provider: 'soak-pool', model: 'soak/synth-live' }]],
]
  .map(
    ([role, chain]) =>
      `          ${role}:\n${chain.map(entry => `            - provider: ${entry.provider}\n              model: ${entry.model}`).join('\n')}`,
  )
  .join('\n')

const yml = `# Soak overlay for the 2026-11-24 hang-shape round.
#
# Generated by gen-patch.mjs. Fake endpoints 127.0.0.1:18591 (the hanging route
# under test), :18592 (401, unused), :18593 (proxy to the machine's own gateway
# 127.0.0.1:18088); every completion is counted per (port, model) in the
# gateway log. The plugin row is INSERTED (the headless profile has no such
# bundle) and points at this repository's built lib/index.js, read-only.
#
# No guardianModel on purpose: a guardian route appends a 300 s wait slice to
# every timed-out call and would destroy the childTimeoutMs measurement.

- id: llm-deepseek
  name: '@deepseek-ai/dsh-llm-deepseek-api-key'
  disabled: true
- id: llm-deepseek-account
  name: '@deepseek-ai/dsh-llm-deepseek-account'
  disabled: true

- id: llm-pi-ai
  name: "@deepseek-ai/dsh-llm-pi-ai"
  config:
    providers:
${live}
${pool}
${hang}
${auth}

- id: agent-default-model
  name: "@deepseek-ai/dsh-agent-default-model"
  config:
    provider: soak-live
    model: ${LIVE_MODEL}

- id: workflow-ptc
  name: '@deepseek-ai/dsh-workflow-ptc'
  config:
    provider: spawn
  disabled: false

- insert:
    - id: grok-workflow
      name: ${PLUGIN_ENTRY}
      config:
        mode: full
        grokDefault: 'off'
        maxConcurrency: 1
        timeoutMs: 1800000
        childTimeoutMs: ${CHILD_TIMEOUT_MS}
        loopEnabled: false
        roles:
${roles}
`

const path = join(here, `scenario-hang${SUFFIX}.yml`)
writeFileSync(path, yml)
console.log(`${path}: childTimeoutMs=${CHILD_TIMEOUT_MS} liveModel=${LIVE_MODEL}`)
