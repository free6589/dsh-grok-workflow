/**
 * End-to-end `/compact` verification in a fresh DSH profile.
 *
 * What is real: the profile (created from the `sdk` template, plugin installed
 * as a bundle row), the DSH Loader, the plugin's `agent/pre-step` gate, the
 * agent loop, the session journal on disk, the token meter, and the `/compact`
 * command reached through the SDK runtime's `session/query` dispatch.
 *
 * What is mocked: the model only — a local HTTP server answering
 * OpenAI-completions requests (see `fake-model.mjs`).
 *
 * The script fails (exit 1) when the `/compact` answer carries the meter's
 * pairing error or when an `assistant/message` sits outside an open step.
 *
 * Usage:
 *   node drive.mjs --home <DSH_HOME> --profile <name> [--team] [--json]
 *
 * `--team` sends a message that names the team tier, which is the pre-step path
 * that used to write the unpaired receipt.
 */

import { spawn } from 'node:child_process'
import { createInterface } from 'node:readline'
import { mkdirSync, writeFileSync } from 'node:fs'
import { randomUUID } from 'node:crypto'
import path from 'node:path'

const args = process.argv.slice(2)
const opt = name => {
  const index = args.indexOf(`--${name}`)
  return index === -1 ? undefined : args[index + 1]
}
const home = opt('home')
const profile = opt('profile')
const resume = opt('resume')
if (home === undefined || profile === undefined) throw new Error('usage: node drive.mjs --home <DSH_HOME> --profile <name> [--team] [--resume <sessionId>]')
const team = args.includes('--team')
const outDir = path.dirname(new URL(import.meta.url).pathname)
const repo = path.resolve(outDir, '../../..')

/* ------------------------------------------------------------ fake model -- */

const modelPort = 41000 + Math.floor(Math.random() * 2000)
const model = spawn(process.execPath, [path.join(outDir, 'fake-model.mjs'), String(modelPort)], { stdio: ['ignore', 'pipe', 'inherit'] })
const modelReady = new Promise(resolve => {
  const read = createInterface({ input: model.stdout })
  read.on('line', line => {
    const match = /^READY (\d+)$/.exec(line)
    if (match !== null) resolve(Number(match[1]))
  })
})
const port = await modelReady
const modelBase = `http://127.0.0.1:${port}/v1`

/* --------------------------------------------------------------- overlay -- */

const patchPath = path.join(home, 'compact-e2e.patch.yml')
mkdirSync(home, { recursive: true })
writeFileSync(patchPath, `# Generated by .rsi/evidence/compact-e2e/drive.mjs — ephemeral, inside the DSH home.
- id: llm-pi-ai
  config:
    providers:
      compactfix-local:
        displayName: Compactfix Local
        api: openai-completions
        baseURL: ${modelBase}
        apiKeyEnv: COMPACTFIX_LOCAL_KEY
        models:
          - id: compactfix/local
            name: Compactfix Local
            contextWindow: 131072
- id: agent-default-model
  config:
    provider: compactfix-local
    model: compactfix/local
- id: grok-workflow
  config:
    mode: triage
    grokDefault: on
    maxTasks: 20
    timeoutMs: 45000
`)

/* ---------------------------------------------------------------- client -- */

const dsh = spawn('dsh', ['--profile', profile, '--patch', patchPath], {
  cwd: repo,
  env: {
    ...process.env,
    DSH_HOME: home,
    // A placeholder, not a credential: the local stub accepts anything, and the
    // real key never exists in this run.
    COMPACTFIX_LOCAL_KEY: 'local-stub-not-a-credential',
  },
  stdio: ['pipe', 'pipe', 'pipe'],
})

const events = []
const notifications = []
let stderr = ''
dsh.stderr.on('data', chunk => { stderr += chunk.toString('utf8') })

const pending = new Map()
let nextId = 1
const rl = createInterface({ input: dsh.stdout })
rl.on('line', line => {
  let frame
  try {
    frame = JSON.parse(line)
  } catch {
    return
  }
  if (typeof frame.id === 'number' && typeof frame.method === 'string') {
    // Server-to-client request; none are needed by this driver.
    dsh.stdin.write(`${JSON.stringify({ jsonrpc: '2.0', id: frame.id, error: { code: -32601, message: 'unsupported' } })}\n`)
    return
  }
  if (typeof frame.id === 'number') {
    const waiter = pending.get(frame.id)
    if (waiter !== undefined) {
      pending.delete(frame.id)
      if (frame.error !== undefined) waiter.reject(new Error(`${frame.error.message}`))
      else waiter.resolve(frame.result)
    }
    return
  }
  if (typeof frame.method === 'string') {
    notifications.push(frame)
    if (frame.method === 'session.event' && frame.params?.event !== undefined) events.push(frame.params.event)
  }
})

function request(method, params, timeoutMs = 180000) {
  const id = nextId++
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => {
      pending.delete(id)
      reject(new Error(`${method} timed out after ${timeoutMs}ms`))
    }, timeoutMs)
    pending.set(id, {
      resolve: value => { clearTimeout(timer); resolve(value) },
      reject: error => { clearTimeout(timer); reject(error) },
    })
    dsh.stdin.write(`${JSON.stringify({ jsonrpc: '2.0', id, method, params })}\n`)
  })
}

const sessionId = resume ?? randomUUID()
const summary = { profile, home, sessionId, resumed: resume !== undefined, teamTierRequested: team }

try {
  summary.initialize = await request('initialize', {
    cwd: repo,
    provider: 'compactfix-local',
    model: 'compactfix/local',
    approvalRequests: false,
  })

  if (resume !== undefined) {
    // Replay an existing journal: the only work is the real `/compact` command
    // over it, which is where the meter's pairing rule fires.
    summary.resume = await request('session/resume', { sessionId })
  } else {
    const task = team
      ? '用团队把 README 里的一句话改得更短，只改那一句。'
      : '请用一句话说明这个工作区里有什么。'
    const promptResult = await request('session/query', {
      sessionId,
      contentBlocks: [{ type: 'text', text: task }],
    })
    summary.prompt = promptResult
    summary.wait = await request('session/wait', { sessionId }, 240000)
  }

  summary.compact = await request('session/query', {
    sessionId,
    contentBlocks: [{ type: 'text', text: '/compact' }],
  }, 240000)

  const assistantTexts = events
    .filter(event => event.type === 'assistant/message')
    .map(event => event.data?.message?.content?.filter?.(part => part.type === 'text').map(part => part.text).join('') ?? '')
  summary.assistantTexts = assistantTexts

  // --- pairing invariant, computed from the journal the run actually wrote ---
  const open = new Map()
  const orphans = []
  for (const event of events) {
    const key = `${event.data?.turn}:${event.data?.step}`
    if (event.type === 'step/start') open.set(key, true)
    else if (event.type === 'step/end') open.delete(key)
    else if (event.type === 'assistant/message' && open.get(key) !== true) {
      orphans.push({ seq: event.seq, turn: event.data?.turn, step: event.data?.step, source: event.data?.message?.source?.model })
    }
  }
  summary.pairing = { orphanAssistantRows: orphans, checkedEvents: events.length }

  const compactText = JSON.stringify(summary.compact ?? '')
  summary.meterErrorInCompact = /has no matching step\/start event/.test(compactText)
  summary.toolWorkflowEvents = events
    .filter(event => String(event.type).startsWith('tool-workflow/'))
    .map(event => event.type)
  summary.turnEnded = events.some(event => event.type === 'turn/end')

  await request('shutdown', {}, 60000).catch(() => {})
} catch (error) {
  summary.error = String(error?.message ?? error)
} finally {
  model.kill('SIGTERM')
  dsh.kill('SIGTERM')
}

summary.dshStderrTail = stderr.split('\n').filter(line => line.trim() !== '').slice(-40)
// A resumed journal is expected to carry its pre-existing rows, so only a fresh
// run asserts the pairing invariant; both assert the `/compact` outcome.
summary.ok = summary.error === undefined
  && summary.meterErrorInCompact === false
  && (resume !== undefined || summary.pairing?.orphanAssistantRows?.length === 0)
  && (resume !== undefined || summary.turnEnded === true)

console.log(JSON.stringify(summary, null, 2))
process.exitCode = summary.ok ? 0 : 1
