// Verification rig (not product code). Writes the soak overlay for one build.
//   node gen-overlay.mjs <abs path to build's lib/index.js> <out.yml> [model]
//
// Why the row name stays `dsh-grok-workflow` and is not the build path:
// cordis-plugin-include applies a patch row by id and SKIPS it when the row's
// name differs from the composed entry's name ("patch: name mismatch ...,
// skipping"). A build path in `name` therefore silently leaves the profile's
// already-installed package mounted, i.e. measures the wrong artifact. The
// measured build is installed AS that package by install-build.sh, and this
// script records the exact path it must be installed from in `<out>.buildpath`.
//
// The provider points at the machine's own gateway on 127.0.0.1:18088 and reads
// its key from BIFROST_VIRTUAL_KEY in the process environment (never a file).
import { writeFileSync } from 'node:fs'
import { isAbsolute } from 'node:path'

const [libEntry, out, modelArg] = process.argv.slice(2)
if (!libEntry || !out) {
  console.error('usage: node gen-overlay.mjs <lib/index.js> <out.yml> [model]')
  process.exit(2)
}
if (!isAbsolute(libEntry)) {
  console.error(`lib entry must be an absolute path, got: ${libEntry}`)
  process.exit(2)
}

const MODEL = modelArg ?? 'wb/cn:deepseek-v4.1-flash'
const BASE_URL = 'http://127.0.0.1:18088/openai/v1'
const API_KEY_ENV = 'BIFROST_VIRTUAL_KEY'
const ROW_NAME = 'dsh-grok-workflow'

const provider = `      soak-live:
        displayName: Soak live (machine gateway, direct)
        api: openai-completions
        baseURL: ${BASE_URL}
        apiKeyEnv: ${API_KEY_ENV}
        compat:
          supportsDeveloperRole: false
          supportsStore: false
        models:
          - id: ${MODEL}
            name: soak live
            contextWindow: 500000
            maxTokens: 65536`

const roles = ['planner', 'worker', 'verifier', 'supervisor', 'synthesizer']
  .map((role) => `      ${role}:\n        - provider: soak-live\n          model: ${MODEL}`)
  .join('\n')

const yml = `# Soak overlay — build under test (installed as ${ROW_NAME}): ${libEntry}
# Generated by gen-overlay.mjs; never commit, never point at the live ~/.dsh.
- id: llm-deepseek
  name: '@deepseek-ai/dsh-llm-deepseek-api-key'
  disabled: true
- id: llm-deepseek-account
  name: '@deepseek-ai/dsh-llm-deepseek-account'
  disabled: true

- id: llm-pi-ai
  name: "@deepseek-ai/dsh-llm-pi-ai"
  config:
    providers:
${provider}

- id: agent-default-model
  name: "@deepseek-ai/dsh-agent-default-model"
  config:
    provider: soak-live
    model: ${MODEL}

- id: workflow-ptc
  name: '@deepseek-ai/dsh-workflow-ptc'
  config:
    provider: spawn
  disabled: false

# The plugin row: same id AND same name as the profile row, so this is an
# in-place update of that row (no second mount, no duplicate tool registration).
- id: grok-workflow
  name: ${ROW_NAME}
  config:
    mode: full
    grokDefault: 'on'
    maxConcurrency: 2
    timeoutMs: 1200000
    childTimeoutMs: 420000
    loopEnabled: false
    roles:
${roles}
    guardianModel:
      provider: soak-live
      model: ${MODEL}
`

writeFileSync(out, yml)
writeFileSync(`${out}.buildpath`, `${libEntry}\n`)
console.log(`overlay written: ${out}`)
console.log(`  lib        = ${libEntry}`)
console.log(`  model      = ${MODEL}`)
console.log(`  baseURL    = ${BASE_URL}`)
console.log(`  apiKeyEnv  = ${API_KEY_ENV} (value never written)`)
