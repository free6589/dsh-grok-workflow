// Generates the three soak overlays from one table, so the only thing that
// differs between scenarios is the role chain — the rig is otherwise identical.
//
//   node gen-patch.mjs
//
// Writes scenario-1.yml / scenario-2.yml / scenario-3.yml next to this file.
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const PLUGIN_ENTRY = '/home/fish/projects_mine/dsh-grok-workflow/.tmp/wt-rel-0.13.29/lib/index.js'

const LIVE = { provider: 'soak-pool', model: 'soak/plan-live' }
const CHILD_TIMEOUT_MS = Number(process.env.CHILD_TIMEOUT_MS ?? 150000)
// The outer agent talks to the machine's gateway directly, so its model id has to be
// one that gateway really serves right now; every workflow leg goes through the fake
// gateway, which rewrites the soak id to this same model.
const LIVE_MODEL = process.env.SOAK_LIVE_MODEL ?? 'wb/cn:deepseek-v4.1-flash'

const SCENARIOS = {
  1: {
    title: 'planner rescue: planner chain [hang, live], no caller tasks',
    childTimeoutMs: CHILD_TIMEOUT_MS,
    roles: {
      planner: [
        { provider: 'soak-hang', model: 'soak/hang-always' },
        { provider: 'soak-pool', model: 'soak/plan-live' },
      ],
      worker: [{ provider: 'soak-pool', model: 'soak/work-live' }],
      verifier: [{ provider: 'soak-pool', model: 'soak/judge-live' }],
      supervisor: [{ provider: 'soak-pool', model: 'soak/sup-live' }],
      synthesizer: [{ provider: 'soak-pool', model: 'soak/synth-live' }],
    },
  },
  2: {
    title: 'judge re-fire: verifier single route hangs once then answers; worker counted',
    childTimeoutMs: CHILD_TIMEOUT_MS,
    roles: {
      planner: [LIVE],
      worker: [{ provider: 'soak-pool', model: 'soak/work-live' }],
      verifier: [{ provider: 'soak-hang', model: 'soak/judge-hang' }],
      supervisor: [{ provider: 'soak-pool', model: 'soak/sup-live' }],
      synthesizer: [{ provider: 'soak-pool', model: 'soak/synth-live' }],
    },
  },
  3: {
    title: 'refused key: worker route is the 401 endpoint only',
    childTimeoutMs: CHILD_TIMEOUT_MS,
    roles: {
      planner: [LIVE],
      worker: [{ provider: 'soak-auth', model: 'soak/auth-bad' }],
      verifier: [{ provider: 'soak-pool', model: 'soak/judge-live' }],
      supervisor: [{ provider: 'soak-pool', model: 'soak/sup-live' }],
      synthesizer: [{ provider: 'soak-pool', model: 'soak/synth-live' }],
    },
  },
}

function providerBlock(id, display, port, models) {
  const entries = models
    .map(model => `          - id: ${model}\n            name: ${model}\n            contextWindow: 500000\n            maxTokens: 65536`)
    .join('\n')
  return `      ${id}:
        displayName: ${display}
        api: openai-completions
        baseURL: http://127.0.0.1:${port}/openai/v1
        apiKeyEnv: BIFROST_VIRTUAL_KEY
        compat:
          supportsDeveloperRole: false
          supportsStore: false
        models:
${entries}`
}

function roleBlock(role, chain) {
  return `          ${role}:\n${chain.map(entry => `            - provider: ${entry.provider}\n              model: ${entry.model}`).join('\n')}`
}

function render(n, scenario) {
  const live = `      soak-live:
        displayName: Soak live (the machine's own gateway, direct — the outer agent uses this)
        api: openai-completions
        baseURL: http://127.0.0.1:18088/openai/v1
        apiKeyEnv: BIFROST_VIRTUAL_KEY
        compat:
          supportsDeveloperRole: false
          supportsStore: false
        models:
          - id: ${LIVE_MODEL}
            name: soak live flash
            contextWindow: 500000
            maxTokens: 65536`
  const pool = providerBlock('soak-pool', 'Soak pool (18493, proxies to the live gateway)', 18493, [
    'soak/plan-live',
    'soak/work-live',
    'soak/judge-live',
    'soak/sup-live',
    'soak/synth-live',
  ])
  const hang = providerBlock('soak-hang', 'Soak hang 18491 — hang-once models, plus one that never answers', 18491, [
    'soak/plan-hang',
    'soak/judge-hang',
    'soak/hang-always',
  ])
  const auth = providerBlock('soak-auth', 'Soak auth (18492, every completion 401)', 18492, ['soak/auth-bad'])
  const roles = Object.entries(scenario.roles).map(([role, chain]) => roleBlock(role, chain)).join('\n')
  return `# Soak overlay for release/0.13.29 — scenario ${n}: ${scenario.title}
#
# Generated by gen-patch.mjs. Fake endpoints 127.0.0.1:18491 (hang-then-proxy),
# :18492 (401), :18493 (proxy to the machine's gateway); every completion is
# counted per (port, model) in the gateway log. The plugin row is INSERTED
# (the headless profile has no such bundle) and points at the built lib/ of the
# worktree under test.

- id: llm-deepseek
  name: '@deepseek-ai/dsh-llm-deepseek-api-key'
  disabled: true
- id: llm-deepseek-account
  name: '@deepseek-ai/dsh-llm-deepseek-account'
  disabled: true

- id: llm-pi-ai
  name: "@deepseek-ai/dsh-llm-pi-ai"
  config:
    providers:
${live}
${pool}
${hang}
${auth}

- id: agent-default-model
  name: "@deepseek-ai/dsh-agent-default-model"
  config:
    provider: soak-live
    model: ${LIVE_MODEL}

- id: workflow-ptc
  name: '@deepseek-ai/dsh-workflow-ptc'
  config:
    provider: spawn
  disabled: false

- insert:
    - id: grok-workflow
      name: ${PLUGIN_ENTRY}
      config:
        mode: full
        grokDefault: 'off'
        maxConcurrency: 1
        timeoutMs: 1800000
        childTimeoutMs: ${scenario.childTimeoutMs}
        loopEnabled: false
        roles:
${roles}
`
}

SCENARIOS.timing = {
  title: 'throwaway timing run: the planner leg really runs on the proxy route, 10-minute budget',
  childTimeoutMs: 600000,
  roles: {
    planner: [LIVE],
    worker: [{ provider: 'soak-pool', model: 'soak/work-live' }],
    verifier: [{ provider: 'soak-pool', model: 'soak/judge-live' }],
    supervisor: [{ provider: 'soak-pool', model: 'soak/sup-live' }],
    synthesizer: [{ provider: 'soak-pool', model: 'soak/synth-live' }],
  },
}

for (const [n, scenario] of Object.entries(SCENARIOS)) {
  if (n === 'timing' && process.env.TIMING !== '1') continue
  const path = join(here, `scenario-${n}.yml`)
  writeFileSync(path, render(n, scenario))
  console.log(`${path}: childTimeoutMs=${scenario.childTimeoutMs} (maxRetries is a REMOVED_CONFIG_KEY, fixed at 1)`)
}
