/**
 * `blockIntake: false` must reproduce the tree that existed before the key.
 *
 * `test/block-flag.spec.ts` compares two loads of *this* tree — one that omits the key
 * and one that sets it to `false` — which pins the narrower claim "the key itself
 * decides nothing". It cannot pin the claim acceptance actually makes, because both of
 * its sides are the same source. This file does.
 *
 * `test/fixtures/block-flag-baseline.json` was produced by the **baseline** source
 * (`9b55d2d`, the commit before the block intake existed) running these same eight
 * payloads through the same real host classes, and every decision here is compared to
 * those bytes with `toBe`. So a drift is not "the two loads disagree", it is "this load
 * no longer answers the way the pre-feature tree answered".
 *
 * The artifact is a byte product, not a config file. It is regenerated by a one-shot
 * dump run in a throwaway baseline worktree and copied here verbatim; it is not meant to
 * be read, hand-edited, reformatted, or re-sorted.
 *
 * One thing is normalised and only one: `id`. `createUserMessage` mints a random uuid
 * for the payload before the gate is ever called, so `raw` bytes could never be pinned
 * across runs. Ids are minted by the host and by this file, never by the gate, so
 * collapsing them removes no decision — and the artifact is asserted to contain no uuid.
 */

