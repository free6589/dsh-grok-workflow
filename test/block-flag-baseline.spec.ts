/** The objective a normal case carries. */
const OBJECTIVE = '把接单台子的账本读出来，然后写一句结论'

/* ------------------------------------------------------------------ engine -- */

/**
 * Engine that refuses to run.
 *
 * `apply()` needs the service to exist, and a default load decides a batch without
 * starting anything: if a `start` ever happened here, the decision under comparison
 * would no longer be a routing decision.
 */
const noRunEngine = {
  async start(): Promise<never> {
    throw new Error('block-flag-baseline.spec.ts must not start a workflow run')
  },
}

/* ------------------------------------------------------------------ agent -- */

/** The slice of an agent the chain reads; `session` is the real host class. */
class FakeAgent {
  readonly followups: UserMessage[] = []
  readonly followup = (message: UserMessage): void => { this.followups.push(message) }
  readonly whenIdle = async (): Promise<void> => {}

  constructor(readonly session: Session) {}
}

/* --------------------------------------------------------------- harness -- */

const mountedContexts: Context[] = []

/**
 * Point the loop's operator-stop marker at a path that does not exist.
 *
 * The dump that produced the artifact ran under the same condition, and a heartbeat's
 * routing is decided by the loop brakes. This checkout may carry a real `.rsi/STOP`, so
 * the marker is moved out of the way for the duration of the file and put back after.
 */
const previousStopFile = process.env['GROK_WORKFLOW_STOP_FILE']
process.env['GROK_WORKFLOW_STOP_FILE'] = join(process.cwd(), '.tmp', 'block-flag-baseline', 'STOP-does-not-exist')

/**
 * A throwaway ledger directory for the whole file.
 *
 * The narrow heartbeat listener is installed on every load and writes one line per beat,
 * so without this override a mount that dispatches a heartbeat would write into
 * `$DSH_HOME` (`~/.dsh` on a developer machine). The dump that produced the artifact
 * wrote no ledger at all, and nothing here may either.
 */
const previousLedgerDir = process.env['GROK_WORKFLOW_BLOCK_LEDGER_DIR']
mkdirSync(join(process.cwd(), '.tmp'), { recursive: true })
const ledger = mkdtempSync(join(process.cwd(), '.tmp', 'block-flag-baseline-ledger-'))
process.env['GROK_WORKFLOW_BLOCK_LEDGER_DIR'] = ledger

afterAll(async () => {
  for (const ctx of mountedContexts.splice(0)) {
    try { await ctx.fiber.dispose() } catch { /* already disposed */ }
  }
  if (previousStopFile === undefined) delete process.env['GROK_WORKFLOW_STOP_FILE']
  else process.env['GROK_WORKFLOW_STOP_FILE'] = previousStopFile
  if (previousLedgerDir === undefined) delete process.env['GROK_WORKFLOW_BLOCK_LEDGER_DIR']
  else process.env['GROK_WORKFLOW_BLOCK_LEDGER_DIR'] = previousLedgerDir
  try { rmSync(ledger, { recursive: true, force: true }) } catch { /* already gone */ }
})

interface Mounted { ctx: Context }

/**
 * Mount the plugin the way a profile that says nothing mounts it.
 *
 * No routing keys: this is the load the artifact pins. A case that needs a different
 * shape passes the override explicitly, and the artifact is only meaningful if both
 * sides run the same inputs in the same order on one shared mount.
 */
async function mount(overrides: Record<string, unknown> = {}): Promise<Mounted> {
  const ctx = new Context()
  await ctx.plugin(SystemPrompt)
  await ctx.plugin(ToolRuntime)
  await ctx.plugin({
    name: 'stub-workflow-engine',
    apply(inner: Context) { inner.provide('workflowEngine', noRunEngine) },
  } as never, {} as never)
  apply(ctx as never, { ...overrides })
  mountedContexts.push(ctx)
  return { ctx }
}

/** The session a top-level conversation has: a head, so it is reopenable. */
function headed(id: string): Session {
  const live = Session.create(id as never)
  live.append('step/start', { turn: 1, step: 1 })
  live.append('system/message', { turn: 1, step: 1, message: createSystemMessage('test head') }, { surfaceOp: 'append' })
  live.append('step/end', { turn: 1, step: 1 })
  return live
}

function userMessage(text: string): UserMessage {
  return createUserMessage({ content: [{ type: 'text', text }], source: { kind: 'user' } as never }) as UserMessage
}

function scheduleMessage(text: string): UserMessage {
  return createUserMessage({
    content: [{ type: 'text', text }],
    source: { kind: 'schedule' } as never,
  }) as UserMessage
}

function systemMessage(text: string): UserMessage {
  return createUserMessage({
    content: [{ type: 'text', text }],
    source: { kind: 'plugin' } as never,
  }) as UserMessage
}

interface Decision { kind: string; messages?: UserMessage[]; reason?: string }

/** Drive one payload through the real waterfall with a base callback. */
async function dispatch(
  mounted: Mounted,
  agent: FakeAgent,
  messages: UserMessage[],
  turn = 1,
): Promise<Decision> {
  return await mounted.ctx.waterfall(
    'agent/pre-step',
    { agent, messages, turn, step: 1, signal: new AbortController().signal } as never,
    async () => ({ kind: 'enter', messages }),
  ) as Decision
}

/**
 * The decision as bytes, with the host's own message ids normalised.
 *
 * This is the exact normalisation the artifact was produced with, so the two sides of
 * every comparison below are the same function applied to the same shape.
 */
function stable(decision: Decision): string {
  return JSON.stringify(decision, (key, value) => key === 'id' ? '<id>' : value)
}

/**
 * A readable account of where two byte strings part company.
 *
 * The over-long case is ~32 000 characters of repeated text; printing both sides whole
 * would hide the one character that moved. This reports the offset and a 100-character
 * window from each side instead.
 */
function diverge(baseline: string, flagged: string): string {
  const limit = Math.min(baseline.length, flagged.length)
  let at = 0
  while (at < limit && baseline[at] === flagged[at]) at += 1
  const from = Math.max(0, at - 40)
  const window = (text: string): string => text.slice(from, at + 60)
  return [
    `first difference at character ${at}`,
    `  baseline (${baseline.length} chars): …${window(baseline)}…`,
    `  flagged  (${flagged.length} chars): …${window(flagged)}…`,
  ].join('\n')
}

/* ------------------------------------------------------------------ cases -- */

/**
 * One case: a session and the payload the chain will see.
 *
 * These are the eight payload shapes the artifact was dumped from, unchanged — the
 * artifact is only meaningful if both sides run the same inputs in the same order, on
 * one shared mount, exactly as the dump did.
 */
interface Case {
  name: string
  overrides?: Record<string, unknown>
  messages: () => UserMessage[]
  run: (mounted: Mounted, messages: UserMessage[]) => Promise<Decision>
}

const CASES: Case[] = [
  {
    name: 'an ordinary user message with grok mode off is still an ordinary turn',
    overrides: { grokDefault: 'off' },
    messages: () => [userMessage(OBJECTIVE)],
    run: async (mounted, messages) => await dispatch(mounted, new FakeAgent(headed('sess-flag-user')), messages),
  },
  {
    name: 'a session whose /grok toggle is off keeps its pass-through turn',
    messages: () => [userMessage(OBJECTIVE)],
    run: async (mounted, messages) => {
      const session = headed('sess-flag-toggle')
      expect(setMode(session, { v: 1, enabled: false, turn: 1, setBy: 'command:/grok' }).ok).toBe(true)
      return await dispatch(mounted, new FakeAgent(session), messages)
    },
  },
  {
    name: 'a delegated child session is still an ordinary turn',
    messages: () => [userMessage(OBJECTIVE)],
    run: async (mounted, messages) => {
      const session = headed('sess-flag-subagent')
      // A child's header carries the delegation depth; nothing reads it any more, and
      // the turn must survive it unchanged.
      Object.assign(session, { header: { origin: 'subagent', delegationDepth: 1 } })
      return await dispatch(mounted, new FakeAgent(session), messages)
    },
  },
  {
    name: 'a Host heartbeat stays a continuation, not a request',
    messages: () => [scheduleMessage(`${LOOP_PROMPT_PREFIX} round 2 of 10`)],
    run: async (mounted, messages) => await dispatch(mounted, new FakeAgent(headed('sess-flag-heartbeat')), messages),
  },
  {
    name: 'a repeat dispatch of the same batch keeps the batch it was given',
    messages: () => [userMessage(OBJECTIVE)],
    run: async (mounted, messages) => {
      const agent = new FakeAgent(headed('sess-flag-repeat'))
      const first = await dispatch(mounted, agent, messages)
      expect(first.kind).toBe('enter')
      // Nothing remembers a batch, so the second dispatch answers exactly like the
      // first: the decision is a function of the payload, not of history.
      return await dispatch(mounted, agent, messages, 2)
    },
  },
  {
    name: 'an over-long prompt is handed on unchanged, not refused',
    messages: () => [userMessage('长'.repeat(TASK_LIMITS.objectiveChars + 1))],
    run: async (mounted, messages) => await dispatch(mounted, new FakeAgent(headed('sess-flag-long')), messages),
  },
  {
    name: 'an empty batch is a tool continuation, not a request',
    messages: () => [],
    run: async (mounted, messages) => await dispatch(mounted, new FakeAgent(headed('sess-flag-empty')), messages),
  },
  {
    name: 'a plugin-source message is never read as a user request',
    messages: () => [systemMessage('runtime context')],
    run: async (mounted, messages) => await dispatch(mounted, new FakeAgent(headed('sess-flag-context')), messages),
  },
]

/* --------------------------------------------------------------- artifact -- */

interface BaselineCase {
  name: string
  /** True when the plugin itself appends a message, i.e. mints an id of its own. */
  mints: boolean
  /** The decision, serialised with every `id` collapsed to `"<id>"`. */
  bytes: string
}

interface BaselineFixture {
  format: number
  baseline: string
  normalisation: string
  cases: BaselineCase[]
}

const FIXTURE = JSON.parse(
  readFileSync(new URL('./fixtures/block-flag-baseline.json', import.meta.url), 'utf8'),
) as BaselineFixture

/** Every case, by name, so a renamed payload fails instead of silently skipping. */
const CASES_BY_NAME = new Map(CASES.map(testCase => [testCase.name, testCase]))

/** How many message ids one decision carries, after the normalisation collapsed them. */
function idCount(bytes: string): number {
  return bytes.split('"<id>"').length - 1
}

/** The messages of one pinned decision, parsed back out of the artifact's bytes. */
function messagesOf(bytes: string): { content?: { text?: string }[], source?: { kind?: string } }[] {
  return (JSON.parse(bytes) as { messages?: { content?: { text?: string }[], source?: { kind?: string } }[] }).messages ?? []
}

/* ------------------------------------------------------------------ tests -- */

describe('the default load answers exactly as the artifact says', () => {
  /*
   * One mount is built once, before any case runs, and every case then uses it. That is
   * not tidiness: the artifact was dumped from one mount in this order, so a per-case
   * mount would compare against bytes produced under different conditions.
   */
  let shared: Mounted
  let userOff: Mounted

  beforeAll(async () => {
    shared = await mount()
    userOff = await mount({ grokDefault: 'off' })
  })

  it('pins the eight payloads in the same order as the artifact', () => {
    expect(FIXTURE.cases.map(entry => entry.name)).toEqual(CASES.map(testCase => testCase.name))
  })

  for (const [index, expected] of FIXTURE.cases.entries()) {
    it(`case ${index + 1} · ${expected.name}`, async () => {
      const testCase = CASES_BY_NAME.get(expected.name)
      if (testCase === undefined) throw new Error(`no payload in this file for "${expected.name}"`)
      const target = testCase.overrides?.['grokDefault'] === 'off' ? userOff : shared
      const flagged = stable(await testCase.run(target, testCase.messages()))
      expect(flagged, `${expected.name}: the decision is not the baseline's\n${diverge(expected.bytes, flagged)}`)
        .toBe(expected.bytes)
    })
  }
})

describe('the artifact is a real pin, not a string that matches itself', () => {
  it('carries eight pass-through decisions and no machine-specific bytes', () => {
    expect(FIXTURE.format).toBe(2)
    // The pin's provenance, not a commit sha: the tree had not been committed when the
    // bytes were re-dumped, and a fabricated sha would be worse than a sentence.
    expect(FIXTURE.baseline).toMatch(/^m3\.3: the default load after the front desk was deleted/)
    expect(FIXTURE.normalisation).toBe('JSON.stringify with every "id" key replaced by "<id>"')
    expect(FIXTURE.cases).toHaveLength(8)
    for (const entry of FIXTURE.cases) {
      expect(entry.bytes.length, `${entry.name}: a decision must not be empty`).toBeGreaterThan(0)
      expect(entry.bytes, `${entry.name}: every decision names its kind`).toContain('"kind"')
      // A uuid here would mean a host-minted id leaked into the artifact, and the
      // comparison would then be about one run's id rather than about the decision.
      expect(entry.bytes, `${entry.name}: no random id may reach the artifact`)
        .not.toMatch(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}/)
      // No timestamp, no absolute path: either would make the artifact unfixable.
      expect(entry.bytes, `${entry.name}: no absolute path`).not.toMatch(/\/(?:home|tmp|Users)\//)
      expect(entry.bytes, `${entry.name}: no ISO timestamp`).not.toMatch(/\d{4}-\d{2}-\d{2}T\d{2}:/)
    }
    // M3.3's whole point: every case keeps the turn, and the plugin mints nothing.
    for (const entry of FIXTURE.cases) {
      expect(entry.bytes, `${entry.name}: nothing may refuse a message`).toContain('"kind":"enter"')
      expect(entry.mints, `${entry.name}: the plugin appends no message`).toBe(false)
    }
    // A pass-through carries the payload's own id and no other: one for every case but
    // the empty batch, which carries none. A count that moved would mean something
    // started appending to the batch.
    for (const entry of FIXTURE.cases) {
      if (entry.bytes.includes('"messages":[]')) expect(idCount(entry.bytes), `${entry.name}: no message`).toBe(0)
      else expect(idCount(entry.bytes), `${entry.name}: collapsed id count`).toBe(1)
    }
    // The empty batch is the one decision small enough to pin in full.
    expect(FIXTURE.cases[6]!.bytes).toBe('{"kind":"enter","messages":[]}')
  })

  it('carries the over-long prompt alone, with no notice appended to it', () => {
    // This is the byte difference M3.3 made. The old artifact held a 723-character
    // `grok-workflow` notice after the user's 32 001 characters; the deleted front desk
    // was the only thing that ever wrote it, and a message must now reach the model as
    // it was typed.
    const overLong = FIXTURE.cases[5]!
    const messages = messagesOf(overLong.bytes)
    expect(messages, 'the refused prompt used to carry a second message').toHaveLength(1)
    expect(messages[0]!.source?.kind).toBe('user')
    expect(messages[0]!.content?.[0]?.text).toHaveLength(TASK_LIMITS.objectiveChars + 1)
    expect(overLong.bytes, 'no notice may be appended any more').not.toContain('grok-workflow')
  })

  it('stops matching when one character of the payload changes', async () => {
    const expected = FIXTURE.cases[0]!
    const testCase = CASES_BY_NAME.get(expected.name)!
    // A fresh mount with the untouched payload reproduces the artifact byte for byte,
    // so the mismatch below is the payload and not the mount.
    const clean = await mount({ grokDefault: 'off' })
    const same = stable(await testCase.run(clean, [userMessage(OBJECTIVE)]))
    expect(same).toBe(expected.bytes)

    const altered = await mount({ grokDefault: 'off' })
    const changed = stable(await testCase.run(altered, [userMessage(`${OBJECTIVE}。`)]))
    expect(changed, 'a one-character payload change must break the comparison').not.toBe(expected.bytes)
  })

  it('stops matching when the message source changes from user to plugin', async () => {
    // With the front desk deleted there is no configuration left that can refuse an
    // ordinary message, so the second tamper is the payload's own source: the same text
    // arriving from a plugin is a different decision, and the artifact must not accept
    // it in place of a user turn.
    const expected = FIXTURE.cases[0]!
    const testCase = CASES_BY_NAME.get(expected.name)!
    const fromPlugin = await mount({ grokDefault: 'off' })
    const changed = stable(await testCase.run(fromPlugin, [systemMessage(OBJECTIVE)]))
    expect(changed, 'a plugin-source message must not answer as a user message').not.toBe(expected.bytes)
  })

  it('answers the same bytes when the intake is switched on explicitly', async () => {
    // The new main line: `blockIntake` is on by default, and turning it on changes
    // nothing about a user message. Both sides are compared with the artifact as well,
    // so this is not "two loads of the same code agree" — it is "the intake-on load is
    // still the pinned load".
    const withIntake = await mount({ blockIntake: true })
    for (const [index, expected] of FIXTURE.cases.entries()) {
      const testCase = CASES_BY_NAME.get(expected.name)!
      const target = testCase.overrides?.['grokDefault'] === 'off'
        ? await mount({ blockIntake: true, grokDefault: 'off' })
        : withIntake
      const flagged = stable(await testCase.run(target, testCase.messages()))
      expect(flagged, `case ${index + 1}: the intake must not intercept a message\n${diverge(expected.bytes, flagged)}`)
        .toBe(expected.bytes)
    }
  })
})
