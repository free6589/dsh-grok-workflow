/**
 * The default load changes not one character of these eight payloads.
 *
 * `test/block-flag.spec.ts` compares three loads of *this* tree with each other, so all
 * it can pin is "the switch does not change a decision". It cannot pin the claim M3.3
 * actually makes, because every side of it is the same source. This file does:
 * `test/fixtures/block-flag-baseline.json` holds what a **default load** — no
 * configuration for the routing keys at all — answers for eight payload shapes, and
 * every decision here is compared to those bytes with `toBe`.
 *
 * The artifact was re-pinned by M3.3, which deleted the front desk. The previous
 * revision was a dump of the pre-feature tree, and it carried on the over-long case the
 * 723-character `grok-workflow` notice that the old front desk appended to a refused
 * prompt. That notice does not exist any more: after the deletion there is no admission
 * listener left to refuse anything, so case 6 below asserts the prompt reaches the loop
 * exactly as the user wrote it. That is M3.3's external promise — a user message is
 * never intercepted — and it is why every case in the artifact is `enter` with the
 * payload's own messages and nothing appended.
 *
 * The artifact is a byte product, not a config file. It is regenerated by a one-shot
 * dump run on the tree being pinned and copied here verbatim; it is not meant to be
 * read, hand-edited, reformatted, or re-sorted.
 *
 * One thing is normalised and only one: `id`. `createUserMessage` mints a random uuid
 * for the payload before any listener is called, so `raw` bytes could never be pinned
 * across runs. Ids are minted by the host and by this file, never by the plugin, so
 * collapsing them removes no decision — and the artifact is asserted to contain no uuid.
 */

